/** 截断到 limit 字，并在末尾说明截断了 —— 免得模型以为用户的话说到一半就没了。 */
function clip(text, limit) {
  const s = String(text ?? "").trim();
  if (s.length <= limit) return s;
  return `${s.slice(0, limit)}\n（内容太长，后面截断了）`;
}

/**
 * 把前端带上来的历史整理成合法的消息数组。
 *
 * 前端拿着这份历史，所以这里必须当成不可信输入处理：
 * 只认 user / assistant 两种角色（**不认 system** —— 收 system 等于让页面上的
 * 任何一段文字都能改写助手的身份），空的丢掉，只留最后 MAX_TURNS 条。
 */
export function sanitizeTurns(list) {
  if (!Array.isArray(list)) return [];
  const out = [];
  for (const t of list) {
    const role = t?.role === "assistant" ? "assistant" : t?.role === "user" ? "user" : "";
    if (!role) continue;
    const content = clip(t?.content, MAX_TURN_CHARS);
    if (!content) continue;
    out.push({ role, content });
  }
  return out.slice(-MAX_TURNS);
}

/**
 * 拼出发给模型的完整消息数组。
 *
 * 顺序是固定的：
 *   [1] system —— 身份 + 铁律 + 内置世界书（SYSTEM_PROMPT）
 *   [2] 历史（sanitizeTurns 过的，只有 user / assistant）
 *   [3] user   —— 这一次的提问
 *   [4] system —— TAIL_GUARD，两条硬约束再说一遍
 *
 * @param {{ask: string, turns?: Array, extraNote?: string}} input
 */
export function buildAssistantMessages({ ask, turns, extraNote } = {}) {
  const asked = clip(ask, MAX_ASK_CHARS);
  const head = extraNote ? `${SYSTEM_PROMPT}\n\n<当前状态>\n${extraNote}\n</当前状态>` : SYSTEM_PROMPT;
  return [
    { role: "system", content: head },
    ...sanitizeTurns(turns),
    { role: "user", content: asked },
    { role: "system", content: TAIL_GUARD },
  ];
}

