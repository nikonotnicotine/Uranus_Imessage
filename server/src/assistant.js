/**
 * 助手用哪个模型：**主 LLM**，也就是这条线上第一个能用的角色聊天模型。
 *
 * 用户的原话是「默认使用的是主LLM」。这个程序里没有一个全局的「主模型」字段
 * —— 模型是按角色选的。所以这里的解释是：**按角色顺序找第一个解析得出来的
 * 聊天模型**，那就是用户实际在用的那个。绑了项目的角色优先 —— 那些是真正在
 * 跑的线路，它们的模型必然是通的；没绑项目的角色可能只是个草稿。
 *
 * 解析不出来一个都没有的时候返回 null，调用方据此提示用户先去「连接」里配一个
 * —— 而不是拿空 endpoint 去打上游。
 *
 * @returns {{url:string,key:string,model:string,label:string}|null}
 */
export function resolveAssistantEndpoint(config, resolveEndpoint) {
  const roles = Array.isArray(config?.roles) ? config.roles : [];
  const bound = roles.filter((r) => String(r?.projectRef ?? "").trim());
  for (const role of [...bound, ...roles]) {
    const endpoint = resolveEndpoint(config, role?.chatModel);
    if (endpoint) return endpoint;
  }
  return null;
}
