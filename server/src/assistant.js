/**
 * Uranus 助手 —— 右下角那个气泡背后的答疑机器人。
 *
 * 它解决的是一件很具体的事：这个程序有十几个分区、几十个折叠栏，
 * 一个新用户打开界面看见的是一整墙开关。他不知道「预设」和「世界书」有什么区别，
 * 不知道角色为什么不上线，也不知道报错里那句「没配好」指的是哪个框。
 * 以前这些只能去翻 README，或者去 QQ 群问人。
 *
 * ── 它不是聊天，是查手册 ──
 *
 * 下面 `DOCS` 那张表就是**内置世界书**：一条 = 一个功能，写清「它是干什么的」
 * 和「在哪个分区的哪一栏打开」。用户问什么就把整本书塞进系统提示词里
 * （见 buildAssistMessages）—— 条目总量在几千字量级，不值得为它做关键词检索：
 * 检索漏一条的代价是助手说「我不知道」，而多塞几千 token 的代价只是几分钱。
 *
 * 世界书里**只写界面上找得到的路径**，不写文件名、不写函数名。原因见
 * SYSTEM_PROMPT 里那条铁律：用户报错时，正确的回答永远是「去某一栏打开某个开关」，
 * 绝不是「去改某个 .js 文件」。改代码这条路对新用户来说不是解法，是更大的坑。
 *
 * ── 不落盘 ──
 *
 * 对话历史由前端拿着，每次请求整段发上来（见 index.js 的 /api/assistant/chat）。
 * 服务端这边不存任何东西 —— 关掉气泡就等于结束咨询，刷新页面从头开始。
 * 这和提示词协助模式（promptmode.js，那个要落盘）刚好相反：那个横跨重启、
 * 要保证「重启后下一句话不会被当成角色扮演」；这个纯粹是网页上的一次问答。
 *
 * 和 promptmode.js 一样：这个文件**不 import imessage.js**（循环依赖）。
 */

